"""Reproject Natural Earth's hypsometric world raster into a Europe map.

  python -I make_map.py <HYP_LR_SR_W_DR.tif> <out.jpg> <out.json>

The map is a Lambert azimuthal equal-area projection centred on 52N 22E, the
projection school atlases use for Europe, so the shapes look right instead of
the stretched look an equirectangular crop has up north. The JSON holds the
numbers the page needs to put latitude and longitude onto the picture.
"""

import json
import math
import sys

import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None

LAT0, LON0 = 52.0, 22.0
# The picture, in km from the centre: Portugal to the Pechora and lake Van,
# Crete to the North Cape.
XMIN, XMAX, YMIN, YMAX = -2750.0, 2300.0, -1950.0, 2250.0
WIDTH = 2600            # output pixels
R = 6371.0              # km, so map units are kilometres at the centre
PIX_DEG = 0.0222222222222222   # the raster's pixel size, from its .tfw


def forward(lat, lon):
    la, lo = np.radians(lat), np.radians(lon)
    la0, lo0 = math.radians(LAT0), math.radians(LON0)
    k = np.sqrt(2.0 / (1.0 + np.sin(la0) * np.sin(la) + np.cos(la0) * np.cos(la) * np.cos(lo - lo0)))
    x = R * k * np.cos(la) * np.sin(lo - lo0)
    y = R * k * (np.cos(la0) * np.sin(la) - np.sin(la0) * np.cos(la) * np.cos(lo - lo0))
    return x, y


def inverse(x, y):
    la0, lo0 = math.radians(LAT0), math.radians(LON0)
    rho = np.hypot(x, y) / R
    rho = np.minimum(rho, 2.0)
    c = 2.0 * np.arcsin(rho / 2.0)
    safe = np.where(rho == 0, 1.0, rho)
    lat = np.arcsin(np.clip(np.cos(c) * math.sin(la0) + (y / R) * np.sin(c) * math.cos(la0) / safe, -1, 1))
    lon = lo0 + np.arctan2((x / R) * np.sin(c), safe * math.cos(la0) * np.cos(c) - (y / R) * math.sin(la0) * np.sin(c))
    return np.degrees(lat), np.degrees(lon)


def main():
    src_path, out_jpg, out_json = sys.argv[1:4]
    xmin, xmax, ymin, ymax = XMIN, XMAX, YMIN, YMAX
    scale = WIDTH / (xmax - xmin)                # px per km
    height = int(round((ymax - ymin) * scale))
    print(f"extent x {xmin:.0f}..{xmax:.0f} km, y {ymin:.0f}..{ymax:.0f} km -> {WIDTH}x{height} px, {1/scale:.2f} km/px")

    # The lat/lon the corners and edges reach, to crop the source raster.
    ex = np.array([xmin, xmax, xmin, xmax, 0, 0, xmin, xmax])
    ey = np.array([ymin, ymin, ymax, ymax, ymin, ymax, 0, 0])
    elat, elon = inverse(ex, ey)
    lat_lo, lat_hi = float(elat.min()) - 2, float(elat.max()) + 2
    lon_lo, lon_hi = float(elon.min()) - 2, float(elon.max()) + 2
    print(f"covers lat {lat_lo:.1f}..{lat_hi:.1f}, lon {lon_lo:.1f}..{lon_hi:.1f}")

    print("loading raster")
    src = Image.open(src_path).convert("RGB")
    sw, sh = src.size
    c0 = max(0, int((lon_lo + 180) / PIX_DEG))
    c1 = min(sw, int((lon_hi + 180) / PIX_DEG) + 1)
    r0 = max(0, int((90 - lat_hi) / PIX_DEG))
    r1 = min(sh, int((90 - lat_lo) / PIX_DEG) + 1)
    crop = np.asarray(src.crop((c0, r0, c1, r1)), dtype=np.float32)
    del src
    ch, cw = crop.shape[:2]
    print(f"source crop {cw}x{ch}")

    print("reprojecting")
    out = np.zeros((height, WIDTH, 3), dtype=np.uint8)
    rows = np.arange(height)
    cols = np.arange(WIDTH)
    for band in range(0, height, 256):
        rr = rows[band:band + 256]
        yy = ymax - (rr + 0.5) / scale
        xx = xmin + (cols + 0.5) / scale
        X, Y = np.meshgrid(xx, yy)
        lat, lon = inverse(X, Y)
        # source pixel coordinates inside the crop
        fx = (lon + 180.0) / PIX_DEG - c0 - 0.5
        fy = (90.0 - lat) / PIX_DEG - r0 - 0.5
        fx = np.clip(fx, 0, cw - 1.001)
        fy = np.clip(fy, 0, ch - 1.001)
        x0 = np.floor(fx).astype(np.int32)
        y0 = np.floor(fy).astype(np.int32)
        tx = (fx - x0)[..., None]
        ty = (fy - y0)[..., None]
        p = (crop[y0, x0] * (1 - tx) * (1 - ty) + crop[y0, x0 + 1] * tx * (1 - ty)
             + crop[y0 + 1, x0] * (1 - tx) * ty + crop[y0 + 1, x0 + 1] * tx * ty)
        out[band:band + len(rr)] = np.clip(p + 0.5, 0, 255).astype(np.uint8)

    Image.fromarray(out).save(out_jpg, quality=84, optimize=True, progressive=True)
    meta = {"lat0": LAT0, "lon0": LON0, "R": R, "xmin": xmin, "ymax": ymax,
            "scale": scale, "width": WIDTH, "height": height}
    with open(out_json, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/make_map.py: how the page puts latitude and longitude onto map/europe.jpg.\n")
        f.write("const MAP = " + json.dumps(meta) + ";\n")
    import os
    print(f"wrote {out_jpg} ({os.path.getsize(out_jpg)} bytes) and {out_json}")


if __name__ == "__main__":
    main()
